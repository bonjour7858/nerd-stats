let currentLang = 'en';

function setLanguage(lang) {
  const targetLang = translations[lang] ? lang : 'en';
  currentLang = targetLang;
  document.documentElement.lang = targetLang;
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[targetLang] && translations[targetLang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[targetLang][key];
      } else {
        el.innerText = translations[targetLang][key];
      }
    }
  });

  const selector = document.getElementById('langSelect');
  if (selector) selector.value = targetLang;
}

function initI18n() {
  const userLang = navigator.language.slice(0, 2);
  const supported = Object.keys(translations);
  const defaultLang = supported.includes(userLang) ? userLang : 'en';
  setLanguage(defaultLang);
}

function formatLocaleNumber(num) {
  if (!num || isNaN(num)) return "0";
  return new Intl.NumberFormat(currentLang).format(num);
}
